#!/bin/sh
# Set up <WORK>/vitabrowser-work from nothing, from GitHub only, at pinned revisions.
#
# The original work tree was assembled by hand from git.netsurf-browser.org
# (docs/phase-0/01, 02), and its revisions were never recorded. This script
# is the reproducible version: a fresh machine -- including a sandboxed cloud
# runner that cannot reach netsurf-browser.org, savannah or curl.se -- gets a
# tree the committed patch stack applies to (215/215) and the simulator
# builds from. Verified 2026-09-27.
#
# What it does, and why each step is needed:
#   1. clones NetSurf's libraries from the github.com/netsurf-browser mirrors,
#      pinned (every pin predates the 2026-09-20 project start);
#   2. libutf8proc: NetSurf's fork is not mirrored on GitHub. Upstream
#      utf8proc (JuliaStrings) has the same API (utils/idna.c uses four
#      functions), so it is built static with a GNUmakefile shim that honours
#      build-patched.sh's `make install PREFIX=` and installs the header
#      where NetSurf looks for it (include/libutf8proc/utf8proc.h);
#   3. MacSurf's browser/ tree at the pinned 55e64fa (for split-patches.py);
#   4. builds the five core libraries IN PLACE once. The committed MacSurf
#      patches were generated against trees that had been built, so they
#      patch generated-but-gitignored files (libcss's autogenerated_*.c,
#      libhubbub's autogenerated-element-type.c). Without this build,
#      libcss/08 and libhubbub/04 fail with "can't find file to patch".
#      The trees stay git-clean (the outputs are ignored), so
#      build-patched.sh's pristine check still passes.
#
# Needs: git, gcc, make, perl, gperf, flex, bison, pkg-config, python3.
# Then: SKIP_REGEN=1 tools/build-patched.sh && tools/run-vita-sim.sh
# (see docs/phase-0/13-cloud-rebuild.md).
#
# Usage: WORK=<WORK>/vitabrowser-work tools/bootstrap-work.sh
set -e
WORK="${WORK:-$HOME/vitabrowser-work}"
GH=https://github.com

# name  revision
PINS="
libwapcaplet   c7c128d3eb3223b216c974471f82e9337fbcf4ba
libparserutils 6b0cbf086ca8eb8fe74b69f0c9ecf274eb2397ca
libhubbub      6651b8cf87a4aa87bcdb2ff024a02659cd3f9402
libcss         499f1c4601ad39942fd1b2204053a387bec9b989
libdom         f69781e1f062444b5af3f62d431d7d94018da53b
netsurf        39da3c3a40af4566d86500ff3052dfdc7f9a0378
libnsutils     0bd39060740b6163bd50875326654a722df97eb2
libnsgif       22e99eb6818b1284d0f3ff1b7f46159e87221220
libnsbmp       ea063c9f46acb43e90208da14073332b505ef7e7
libnspsl       82815c2bc7fd70d1b6afccfa89a9a0f3fa73db8a
libsvgtiny     073283b29dd800e4d938db42af7e131db848bf3b
nsgenbind      44c6736937ae17d4065d02959b82813b8f06a51e
"
BUILDSYSTEM_REV=0005ae300283ff01c2e2b05e7376b3e55dea21f7
UTF8PROC_TAG=v2.9.0
MACSURF_REV=55e64fac243b22395274fa2603e1800d271dbbaf

for t in git gcc make perl gperf flex bison pkg-config python3; do
	command -v "$t" > /dev/null || { echo "bootstrap-work.sh: needs $t"; exit 1; }
done

# clone_at <url> <dir> <rev>: idempotent; an existing clone is moved to rev.
clone_at() {
	if [ ! -d "$2/.git" ]; then
		git clone -q "$1" "$2"
	fi
	git -C "$2" checkout -q "$3"
}

mkdir -p "$WORK/upstream"
echo "== NetSurf libraries (github.com/netsurf-browser) =="
echo "$PINS" | while read -r name rev; do
	[ -n "$name" ] || continue
	clone_at "$GH/netsurf-browser/$name" "$WORK/upstream/$name" "$rev"
	echo "  $name $(echo "$rev" | cut -c1-9)"
done
clone_at "$GH/netsurf-browser/buildsystem" "$WORK/buildsystem" "$BUILDSYSTEM_REV"
echo "  buildsystem $(echo "$BUILDSYSTEM_REV" | cut -c1-9)"

echo "== libutf8proc (JuliaStrings utf8proc $UTF8PROC_TAG, static) =="
U="$WORK/upstream/libutf8proc"
[ -d "$U/.git" ] || git clone -q --depth 1 -b "$UTF8PROC_TAG" \
	"$GH/JuliaStrings/utf8proc" "$U"
# GNU make reads GNUmakefile before Makefile, so upstream's own Makefile
# (shared library, lower-case `prefix`) is never used. Kept out of git's
# view so the clone stays clean.
cat > "$U/GNUmakefile" <<'EOF'
# VitaBrowser shim (tools/bootstrap-work.sh): static libutf8proc laid out
# the way NetSurf's fork installs it.
PREFIX ?= /usr/local
CC ?= cc
AR ?= ar
libutf8proc.a: utf8proc.c utf8proc.h utf8proc_data.c
	$(CC) $(CFLAGS) -O2 -fPIC -DUTF8PROC_STATIC -c utf8proc.c -o utf8proc.o
	$(AR) rcs $@ utf8proc.o
install: libutf8proc.a
	mkdir -p $(PREFIX)/lib/pkgconfig $(PREFIX)/include/libutf8proc
	cp libutf8proc.a $(PREFIX)/lib/
	cp utf8proc.h $(PREFIX)/include/libutf8proc/
	printf 'prefix=%s\nlibdir=$${prefix}/lib\nincludedir=$${prefix}/include\n\nName: libutf8proc\nDescription: UTF-8 processing (utf8proc)\nVersion: 2.9.0\nLibs: -L$${libdir} -lutf8proc\nCflags: -I$${includedir}/libutf8proc -DUTF8PROC_STATIC\n' \
		'$(PREFIX)' > $(PREFIX)/lib/pkgconfig/libutf8proc.pc
clean:
	rm -f utf8proc.o libutf8proc.a
.PHONY: install clean
EOF
grep -qx GNUmakefile "$U/.git/info/exclude" 2>/dev/null || \
	echo GNUmakefile >> "$U/.git/info/exclude"

echo "== MacSurf browser/ tree at $(echo "$MACSURF_REV" | cut -c1-7) =="
M="$WORK/macsurf-git"
if [ ! -d "$M/.git" ]; then
	git clone -q --no-checkout --filter=blob:none "$GH/mplsllc/macsurf" "$M"
	git -C "$M" sparse-checkout init --cone
	git -C "$M" sparse-checkout set browser
fi
git -C "$M" checkout -q "$MACSURF_REV"
[ -e "$WORK/browser" ] || ln -s "$M/browser" "$WORK/browser"

echo "== core libraries built in place (generated files the stack patches) =="
UP="$WORK/upstream-prefix"
( cd "$WORK/buildsystem" && make install PREFIX="$UP" > /dev/null 2>&1 )
for l in libwapcaplet libparserutils libhubbub libcss libdom; do
	( cd "$WORK/upstream/$l" && \
	  PKG_CONFIG_PATH="$UP/lib/pkgconfig" PATH="$UP/bin:$PATH" \
	  make install PREFIX="$UP" > "$WORK/upstream-build-$l.log" 2>&1 ) \
	  && echo "  $l ok" \
	  || { echo "  $l FAILED (see $WORK/upstream-build-$l.log)"; exit 1; }
	[ -z "$(git -C "$WORK/upstream/$l" status --porcelain)" ] || \
		{ echo "  $l is no longer git-clean after building"; exit 1; }
done
echo "done: $WORK"
