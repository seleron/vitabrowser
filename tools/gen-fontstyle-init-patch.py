#!/usr/bin/env python3
"""Spell out plot_font_style_t's MacSurf-added fields at positional initializers.

MacSurf extends plot_font_style_t with six members -- letter_spacing,
word_spacing, shadow_x, shadow_y, shadow_blur, shadow_color -- but does not
update the positional initializers that predate them, because their CodeWarrior
build does not use -Wmissing-field-initializers.

C zero-fills the remaining fields when an initializer is present, so the code
was never wrong, only implicit. Spelling the fields out keeps the warning
active for the cases where it would catch something real, rather than demoting
it tree-wide.

Designated initializers (local_history.c) are left alone: they name their
fields, so there is nothing to pad.

Usage: WORK=<WORK>/vitabrowser-work tools/gen-fontstyle-init-patch.py
"""
import os
import re
import subprocess
import sys

W = os.path.expanduser(os.environ.get('WORK', '<WORK>/vitabrowser-work'))
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Base is MacSurf's tree, not pristine upstream. Upstream uses DESIGNATED
# initializers here; MacSurf rewrites them positionally for CodeWarrior. This
# patch applies after the generated stack, at which point the tree holds
# MacSurf's content, so that is what the hunk context must match.
UP = os.path.join(W, 'browser', 'netsurf')
OUT = os.path.join(ROOT, 'patches', 'vitabrowser',
                   '05-netsurf-plot-font-style-init.patch')

# Files carrying positional plot_font_style_t initializers. form.c is excluded:
# it is hand-ported, so its copy in $WORK/handport is edited directly.
FILES = [
    'desktop/plot_style.c',
    'desktop/page-info.c',
    'content/handlers/html/box_textarea.c',
]

DECL = re.compile(r'plot_font_style_t[^=;]*=\s*\{')
PAD = [
    '\t0,   /* letter_spacing */',
    '\t0,   /* word_spacing */',
    '\t0,   /* shadow_x */',
    '\t0,   /* shadow_y */',
    '\t0,   /* shadow_blur */',
    '\t0    /* shadow_color */',
]


def pad_initializers(text):
    """Append the six new fields to each positional initializer lacking them."""
    out, i, n = [], 0, 0
    lines = text.splitlines(keepends=True)
    while i < len(lines):
        out.append(lines[i])
        if not DECL.search(lines[i]):
            i += 1
            continue
        # gather the body up to the closing brace
        body, j, depth = [], i + 1, 1
        while j < len(lines):
            depth += lines[j].count('{') - lines[j].count('}')
            if depth == 0:
                break
            body.append(lines[j])
            j += 1
        joined = ''.join(body)
        if '.' in re.sub(r'/\*.*?\*/', '', joined, flags=re.S).replace('...', ''):
            # designated initializer -- nothing to pad
            pass
        if re.search(r'^\s*\.\w+\s*=', joined, re.M):
            out.extend(body)
            out.append(lines[j])
            i = j + 1
            continue
        if 'letter_spacing' in joined:
            out.extend(body)
            out.append(lines[j])
            i = j + 1
            continue
        # positional and short: terminate the last element, then pad
        k = len(body) - 1
        while k >= 0 and not body[k].strip():
            k -= 1
        body[k] = body[k].rstrip('\n').rstrip() + ',\n'
        indent = '\t' if body[k].startswith('\t') else '        '
        body.extend(p.replace('\t', indent, 1) + '\n' for p in PAD)
        out.extend(body)
        out.append(lines[j])
        n += 1
        i = j + 1
    return ''.join(out), n


def main():
    chunks, total = [], 0
    for rel in FILES:
        src = os.path.join(UP, rel)
        if not os.path.exists(src):
            print(f'skip {rel}: not present', file=sys.stderr)
            continue
        text = open(src, errors='replace').read()
        new, n = pad_initializers(text)
        if n == 0:
            print(f'{rel}: nothing to pad')
            continue
        tmp = f'/tmp/fsinit-{os.path.basename(rel)}'
        open(tmp, 'w').write(new)
        d = subprocess.run(['diff', '-u', src, tmp],
                           capture_output=True, text=True).stdout.splitlines(keepends=True)
        os.unlink(tmp)
        if not d:
            continue
        d[0] = f'--- a/{rel}\n'
        d[1] = f'+++ b/{rel}\n'
        chunks.extend(d)
        total += n
        print(f'{rel}: padded {n} initializer(s)')

    with open(OUT, 'w') as fh:
        fh.write('# vitabrowser: spell out plot_font_style_t\'s MacSurf-added fields\n')
        fh.write('#\n')
        fh.write('# Generated by tools/gen-fontstyle-init-patch.py -- regenerate, do not\n')
        fh.write('# hand-edit. MacSurf adds letter_spacing, word_spacing and the four\n')
        fh.write('# shadow_* members but leaves older positional initializers short,\n')
        fh.write('# because CodeWarrior does not use -Wmissing-field-initializers.\n')
        fh.write('#\n')
        fh.write('# C zero-fills the rest, so this is about keeping the warning useful,\n')
        fh.write('# not about fixing a defect. Designated initializers are left alone.\n')
        fh.write('#\n')
        fh.write('# Applies to: netsurf (after the generated stack)\n')
        fh.writelines(chunks)
    print(f'{OUT}: {total} initializers padded')
    return 0


if __name__ == '__main__':
    sys.exit(main())
