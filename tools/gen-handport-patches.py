#!/usr/bin/env python3
"""Generate patches/vitabrowser/ entries for the hand-ported netsurf files.

Those files are excluded from the generated stack (HAND_PORTED in
tools/split-patches.py) because MacSurf's instrumentation in them is
interleaved with real work at a granularity finer than hunks, so mechanical
classification oscillates -- see docs/phase-0/07-netsurf-port.md §9.3.

The edited copies live in $WORK/handport/. This diffs each against UPSTREAM,
which is what the tree actually contains once the generated stack has been
applied, and writes one patch per file.

Usage: WORK=<WORK>/vitabrowser-work tools/gen-handport-patches.py
"""
import os
import subprocess
import sys

W = os.path.expanduser(os.environ.get('WORK', '<WORK>/vitabrowser-work'))
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(W, 'handport')
UP = os.path.join(W, 'upstream', 'netsurf')
OUT = os.path.join(ROOT, 'patches', 'vitabrowser')
REL = 'content/handlers/html'

FILES = ['form.c', 'layout.c', 'interaction.c', 'html.c', 'layout_safe.h',
         'redraw.c', 'script.c']
START = 10          # patch numbers 10+ so the hand ports sort after the fixes


def main():
    os.makedirs(OUT, exist_ok=True)
    for n, fn in enumerate(FILES, start=START):
        edited = os.path.join(SRC, fn)
        if not os.path.exists(edited):
            print(f'skip {fn}: no edited copy', file=sys.stderr)
            continue
        orig = os.path.join(UP, REL, fn)
        if not os.path.exists(orig):
            # A file MacSurf added outright (layout_safe.h). Diff against
            # /dev/null so the patch creates it; otherwise excluding it from
            # the generated stack would simply delete it, and every file that
            # includes it stops compiling.
            orig = '/dev/null'
        d = subprocess.run(['diff', '-u', orig, edited],
                           capture_output=True, text=True)
        body = d.stdout.splitlines(keepends=True)
        if not body:
            print(f'{fn}: identical to upstream, no patch')
            continue
        body[0] = f'--- a/{REL}/{fn}\n'
        body[1] = f'+++ b/{REL}/{fn}\n'
        name = f'{n}-netsurf-{fn.replace(".", "-")}.patch'
        with open(os.path.join(OUT, name), 'w') as fh:
            fh.write(f'# vitabrowser: hand-ported {REL}/{fn}\n')
            fh.write('#\n')
            fh.write('# Generated by tools/gen-handport-patches.py from the edited copy in\n')
            fh.write('# $WORK/handport/. Edit that copy and regenerate; do not edit this\n')
            fh.write('# patch directly.\n')
            fh.write('#\n')
            fh.write('# Applies to: netsurf (after the generated stack)\n')
            fh.writelines(body)
        adds = sum(1 for l in body if l.startswith('+') and not l.startswith('+++'))
        print(f'{name}: +{adds} lines')
    return 0


if __name__ == '__main__':
    sys.exit(main())
