#!/usr/bin/env python3
"""Generate the local patch that teaches libcss's Makefiles about MacSurf's
added property files.

MacSurf builds from MacSurf.mcp, a CodeWarrior project that lists sources
independently, so their own Makefiles never learned about the ~44 property
implementations they added. Nothing compiles those files, and the link fails on
css__cascade_accent_color and friends. Wiring them into the Makefile is our
port work, not theirs, so it lives in patches/vitabrowser/.

Regenerate after changing the stack:
    tools/gen-makefile-patch.py > patches/vitabrowser/01-libcss-makefile.patch
"""
import os
import re
import sys

# Same prefix set the splitter strips; see tools/split-patches.py.
RENAME_PREFIX = re.compile(
    r'^(ns_|hub_|pu_|dom_|css_|p_|s_|libcss_|libhubbub_|'
    r'internal_|utils_|core_)')


def strip_candidates(base):
    """The file itself, then each progressively prefix-stripped form."""
    yield base
    seen, cur = set(), base
    while True:
        nxt = RENAME_PREFIX.sub('', cur, count=1)
        if nxt == cur or nxt in seen:
            return
        seen.add(nxt)
        cur = nxt
        yield nxt

W = os.path.expanduser(os.environ.get('WORK', '<WORK>/vitabrowser-work'))
UP = os.path.join(W, 'upstream', 'libcss')
MS = os.path.join(W, 'browser', 'libcss')

DIRS = [
    ('src/select/properties', 's_'),
    ('src/parse/properties', 'p_'),
    # custom_properties.c implements cascade-time var(); it lives a level up
    # from the property files and is just as absent from the Makefile.
    ('src/parse', ''),
    ('src/select', ''),
]


def added_sources(rel, prefix):
    """MacSurf .c files in this directory with no upstream counterpart."""
    ms_dir, up_dir = os.path.join(MS, rel), os.path.join(UP, rel)
    out = []
    for fn in sorted(os.listdir(ms_dir)):
        if not fn.endswith('.c'):
            continue
        # ag_*.c are MacSurf's committed copies of build output. We regenerate
        # them under their upstream name, so listing them here asks make to
        # build files that do not exist.
        if fn.startswith('ag_'):
            continue
        # A file is only "added" if NO prefix-stripped form of it exists
        # upstream in this directory. Checking one prefix is not enough:
        # src/parse/css_parse.c is a rename of parse.c, and listing it asks
        # make to build a file the stack never creates.
        if any(os.path.exists(os.path.join(up_dir, cand))
               for cand in strip_candidates(fn)):
            continue
        out.append(fn)
    return out


def main():
    print('# vitabrowser: libcss -- build MacSurf\'s added property files')
    print('#')
    print('# Hand-applied after the generated MacSurf stack. MacSurf builds')
    print('# from MacSurf.mcp (CodeWarrior), so their Makefiles never list the')
    print('# property implementations they added; without this the link fails')
    print('# on css__cascade_accent_color and ~43 siblings.')
    print('#')
    print('# Generated by tools/gen-makefile-patch.py -- regenerate, do not edit.')
    print('#')
    for rel, prefix in DIRS:
        files = added_sources(rel, prefix)
        if not files:
            continue
        path = os.path.join(rel, 'Makefile')
        up_mk = os.path.join(UP, path)
        with open(up_mk) as fh:
            lines = fh.read().splitlines()
        # Anchor on the last source line: the entry before the blank line that
        # precedes the trailing include.
        last = max(i for i, l in enumerate(lines)
                   if l.endswith('.c') or l.endswith('.c \\'))
        ctx_before = lines[max(0, last - 2):last + 1]
        added = [f'{f} \\' for f in files]
        print(f'--- a/{path}')
        print(f'+++ b/{path}')
        start = max(0, last - 2) + 1
        print(f'@@ -{start},{len(ctx_before)} +{start},'
              f'{len(ctx_before) + len(files)} @@')
        for l in ctx_before[:-1]:
            print(' ' + l)
        # The old last entry has no trailing backslash; it needs one now.
        print('-' + ctx_before[-1])
        print('+' + ctx_before[-1] + ' \\')
        for i, f in enumerate(files):
            print('+' + (f + ' \\' if i < len(files) - 1 else f))
        print()
    return 0


if __name__ == '__main__':
    sys.exit(main())
