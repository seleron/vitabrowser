#!/usr/bin/env python3
"""Capture a NetSurf plot-instruction stream as a golden file.

Why this exists
---------------
`nsmonkey` emits every paint operation as a line of text:

    PLOT TEXT X 220 Y 143 STR Example Domain
    PLOT RECT X0 0 Y0 0 X1 960 Y1 544

That stream comes from the *same* plotter interface the Vita frontend will
implement (brief section 4), so a layout regression can be caught by diffing
text instead of comparing pixels: no font rasterisation variance, no image
encoding, and a failure names the plot call that moved rather than reporting
"12000 pixels differ". The Vita frontend can emit the identical format over the
UDP log, which is how we diff on-device rendering against the desktop without a
debugger. See docs/phase-0/03-golden-plotstream.md.

Usage:
    tools/plotstream.py --monkey <WORK>/vitabrowser-work/upstream/netsurf/nsmonkey \
                        --url https://example.com/ --out golden/example.plot

Viewport defaults to the Vita's 960x544 front screen, which requires the
two-line monkey patch recorded in docs/phase-0/03-golden-plotstream.md.
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

# Coordinates are the point of the file; volatile ids and poll timings are not.
DROP = re.compile(r'^(GENERIC POLL|GENERIC STARTED|GENERIC CLOSING_DOWN|'
                  r'GENERIC FINISHED|GENERIC EXIT|WINDOW DESTROY)')
# "FOR 0x643e742de6e0" changes every run and must be masked. Require a
# non-alphanumeric before it and >=6 hex digits, or this eats page content:
# the string "200x60" contains "0x60".
PTR = re.compile(r'(?<![0-9A-Za-z])0x[0-9a-f]{6,}')


def capture(monkey, url, load_wait, redraw_wait):
    """Drive nsmonkey to completion and return its full output as a line list.

    Commands are fed on a timed schedule and stdout is collected to a file,
    rather than reading the pipe from a thread. That is deliberate: draining
    monkey's stdout concurrently puts it into an endless re-fetch loop (the
    page never settles and the capture comes back blank). See the doc's
    "Open question" section.
    """
    script = (
        f'printf "WINDOW NEW\\n"; sleep 2; '
        f'printf "WINDOW GO 0 {url}\\n"; sleep {load_wait}; '
        f'printf "WINDOW REDRAW 0\\n"; sleep {redraw_wait}; '
        f'printf "QUIT\\n"'
    )
    with tempfile.NamedTemporaryFile('w+', suffix='.monkey', delete=False) as tf:
        out_path = tf.name
    try:
        # nsmonkey resolves its resource tree relative to the working
        # directory, so it must be run from beside the binary or every page
        # comes back unstyled and nearly empty.
        subprocess.run(
            f'{{ {script}; }} | timeout {load_wait + redraw_wait + 30} '
            f'./{os.path.basename(monkey)} 2>/dev/null > {out_path}',
            shell=True, check=False, cwd=os.path.dirname(os.path.abspath(monkey)))
        with open(out_path) as fh:
            return [l.rstrip('\n') for l in fh]
    finally:
        os.unlink(out_path)


def slice_redraw(lines):
    """Return the lines of the final REDRAW block, inclusive."""
    starts = [i for i, l in enumerate(lines) if l.startswith('WINDOW REDRAW WIN') and l.endswith('START')]
    stops = [i for i, l in enumerate(lines) if l.startswith('WINDOW REDRAW WIN') and l.endswith('STOP')]
    if not starts or not stops:
        return lines
    return lines[starts[-1]:stops[-1] + 1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--monkey', required=True, help='path to nsmonkey')
    ap.add_argument('--url', required=True)
    ap.add_argument('--width', type=int, default=960, help='for the header only')
    ap.add_argument('--height', type=int, default=544)
    ap.add_argument('--out', help='write golden file here (default: stdout)')
    ap.add_argument('--load-wait', type=int, default=12,
                    help='seconds to allow for fetch + layout (default 12)')
    ap.add_argument('--redraw-wait', type=int, default=5)
    ap.add_argument('--all', action='store_true',
                    help='keep the whole session, not just the redraw block')
    ap.add_argument('--raw', action='store_true',
                    help='keep volatile lines (pointers, poll timings)')
    args = ap.parse_args()

    if not os.path.exists(args.monkey):
        print(f'no such monkey binary: {args.monkey}', file=sys.stderr)
        return 2

    lines = capture(args.monkey, args.url, args.load_wait, args.redraw_wait)
    if not args.all:
        lines = slice_redraw(lines)
    if not args.raw:
        lines = [PTR.sub('0xPTR', l) for l in lines if not DROP.match(l)]

    plots = sum(1 for l in lines if l.startswith('PLOT'))
    header = (f'# plotstream {args.url} @ {args.width}x{args.height}\n'
              f'# {plots} plot operations\n'
              f'# generated by tools/plotstream.py -- do not hand-edit\n')
    text = header + '\n'.join(lines) + '\n'

    if args.out:
        with open(args.out, 'w') as fh:
            fh.write(text)
        print(f'{args.out}: {len(lines)} lines, {plots} PLOT ops', file=sys.stderr)
    else:
        sys.stdout.write(text)

    if plots < 3:
        print('warning: suspiciously few plot ops -- page probably did not '
              'load; try a larger --load-wait', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
