#!/usr/bin/env python3
"""Split the MacSurf-vs-upstream divergence into a logical patch stack.

Brief section 14.4 calls for vendoring upstream NetSurf and applying MacSurf's
changes as a documented patch series. tools/regen-patches.sh produces five
whole-library diffs (121,604 lines); this turns those into per-topic patches
with a manifest.

Three classes of change are EXCLUDED rather than ported, because they carry no
semantic value for us:

  renames    MacSurf renamed ~90 files to dodge CodeWarrior filename collisions
             and the classic Mac 31-character limit (errors.h -> ns_errors.h,
             autogenerated_* -> ag_*, utf8.c -> pu_utf8.c). Content is
             byte-identical modulo whitespace. vitaSDK is GCC and has neither
             problem, so porting these would be pure churn.

  generated  Files the NetSurf build generates (ag_*.c from properties.gen via
             mkprops.pl, libhubbub's entities.inc / entities_dict.h). MacSurf
             committed the build output because CodeWarrior cannot run perl.
             We run perl, so we regenerate. Patch the GENERATOR INPUT instead.

  build      Makefiles carrying only rename bookkeeping.

What remains is real work: the 12 new CSS properties MacSurf implemented, and
genuine modifications to engine source.

Usage:  tools/split-patches.py [--work <WORK>/vitabrowser-work] [--out patches/]
"""
import argparse
import collections
import hashlib
import os
import re
import sys

LIBS = ['libwapcaplet', 'libparserutils', 'libhubbub', 'libcss', 'libdom',
        'netsurf']
FIX_RE = re.compile(r'fixes[0-9]+[a-z]*', re.I)

# Files the build regenerates. Patch the generator input, never the output.
#
# Name alone is not the test. libcss/src/select/autogenerated_computed.h is
# COMMITTED upstream source despite its name -- and it holds
# MACSURF_CALC_SLOT_COUNT and css_computed_transition_data, so excluding it
# broke the build. The reliable rule is whether the file exists in the upstream
# tree: if upstream ships it, it is source and we patch it; if only MacSurf has
# it, it is build output they committed because CodeWarrior cannot run perl.
GENERATED = (
    re.compile(r'/ag_[^/]+\.c$'),
    re.compile(r'/entities(_dict)?\.(inc|h)$'),
    re.compile(r'/aliases\.inc$'),
)


def upstream_tracked(up_root):
    """Paths upstream has under version control.

    Not a filesystem check: we build inside the upstream tree, so generated
    files like entities.inc are present on disk without being source. git is
    the authority on which is which.
    """
    import subprocess
    try:
        out = subprocess.run(['git', 'ls-files'], cwd=up_root, text=True,
                             capture_output=True, check=True).stdout
        return set(out.split())
    except Exception:
        return set()


def is_generated(rel, tracked):
    if rel in tracked:
        return False                      # upstream ships it -> it is source
    return any(rx.search('/' + rel) for rx in GENERATED)


def content_sig(path):
    """Whitespace-insensitive content hash, for rename detection."""
    try:
        with open(path, 'rb') as fh:
            return hashlib.md5(b' '.join(fh.read().split())).hexdigest()
    except OSError:
        return None


INCLUDE_LINE = re.compile(r'^(\+\s*#\s*include\s*)([<"])([^>"]+)([>"])(.*)$')


def build_include_index(upstream):
    """Index every upstream header by the names MacSurf might call it.

    MacSurf mangles include targets three ways, and chasing them by guessing
    prefixes does not converge -- stylesheet.h became css_internal_stylesheet.h
    and select/font_face.h became css_internal_select_font_face.h. So index the
    upstream tree by every alias it could be referred to under, and resolve
    against that instead:

      src/select/font_face.h  ->  "select/font_face.h"           (real path)
                                  "font_face.h"                  (basename)
                                  "select_font_face.h"           (flattened)

    Lookups then strip any leading prefix run and try each alias.
    """
    index = {}
    for dirpath, dirnames, filenames in os.walk(upstream):
        dirnames[:] = [d for d in dirnames
                       if d not in ('.git', 'test') and not d.startswith('build-')]
        for fn in filenames:
            if not fn.endswith(('.h', '.c', '.inc')):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), upstream)
            # Two include conventions to cover. The libraries put sources under
            # src/ and include/ and include relative to those. netsurf has no
            # src/ at all -- it is content/, desktop/, utils/ -- and includes
            # relative to the tree root. Index both forms, or every
            # #include "utils/errors.h" in netsurf resolves to nothing.
            # Stripped form first: index.setdefault keeps the first mapping,
            # and a library's own sources say #include "stylesheet.h", not
            # "src/stylesheet.h". The raw path is the fallback that covers
            # netsurf.
            forms = []
            for root in ('src/', 'include/'):
                if rel.startswith(root):
                    forms.append(rel[len(root):])
                    break
            forms.append(rel)
            for inner in forms:
                index.setdefault(inner, inner)
                index.setdefault(os.path.basename(inner), inner)
                index.setdefault(inner.replace('/', '_'), inner)
    return index


PREFIX_RUN = re.compile(
    r'^(?:ns_|hub_|pu_|dom_|css_|p_|s_|libcss_|libhubbub_|'
    r'internal_|utils_|core_)+')


def resolve_include(target, index):
    """Map a MacSurf include target back to its upstream path, or None."""
    base = os.path.basename(target)
    if target in index and index[target] == target:
        return None                      # already correct
    for cand in (target, base):
        if cand in index:
            return index[cand]
    stripped = base
    while True:
        nxt = PREFIX_RUN.sub('', stripped, count=1)
        if nxt == stripped:
            break
        stripped = nxt
        if stripped in index:
            return index[stripped]
    stripped = RENAME_SUFFIX.sub('.h', stripped)
    return index.get(stripped)


def rewrite_includes(lines, index, basename_map):
    """Point added lines back at upstream filenames.

    Two passes. #include directives get the upstream *path* (MacSurf flattens
    include paths, so "hub_parserutilserror.h" must become
    "utils/parserutilserror.h"). Everything else -- Makefile source lists in
    particular -- gets a plain basename swap, or the build would reference
    p_border_radius.c, a rename we deliberately did not port.
    """
    lines = renumber_hunks(keep_standard_includes(keep_bool_decls(lines)))
    out = []
    for line in lines:
        m = INCLUDE_LINE.match(line)
        if m:
            head, ob, path, cb, tail = m.groups()
            fixed = resolve_include(path, index)
            if fixed and fixed != path:
                out.append(f'{head}{ob}{fixed}{cb}{tail}\n')
                continue
        if line.startswith('+') and basename_map:
            for old_base, new_base in basename_map.items():
                if old_base in line:
                    line = re.sub(r'(?<![\w/])' + re.escape(old_base) + r'(?![\w])',
                                  new_base, line)
        out.append(line)
    return out


STD_INCLUDE = re.compile(
    r'^-\s*#\s*include\s*<(stdbool|stdint|stddef|stdlib|string|assert|'
    r'limits|inttypes|stdarg|stdio|math|time)\.h>')

HUNK = re.compile(r'^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$')


def keep_standard_includes(lines):
    """Refuse to port the removal of a standard-library #include.

    MacSurf strips these deliberately -- their own comment reads "stdbool.h
    removed for CW8 C89 -- prefix provides bool" -- because CodeWarrior 8 lacks
    the header and a force-included prefix supplies the type. On GCC the header
    exists and the prefix does not, so porting the removal breaks the build.

    The removal line is converted to context, which keeps the include and
    leaves the hunk valid. Only the new-side count changes.
    """
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        m = HUNK.match(line.rstrip('\n'))
        if not m:
            out.append(line)
            i += 1
            continue

        # Collect the hunk body, rewriting standard-include removals.
        old_start, old_len, new_start, new_len, tail = m.groups()
        body = []
        j = i + 1
        rescued = 0
        while j < len(lines) and not HUNK.match(lines[j].rstrip('\n')) \
                and not lines[j].startswith(('diff ', '--- ', '+++ ')):
            bl = lines[j]
            if STD_INCLUDE.match(bl):
                bl = ' ' + bl[1:]
                rescued += 1
            body.append(bl)
            j += 1

        if rescued:
            nl = int(new_len if new_len is not None else 1) + rescued
            ol = old_len if old_len is not None else '1'
            out.append(f'@@ -{old_start},{ol} +{new_start},{nl} @@{tail}\n')
        else:
            out.append(line)
        out.extend(body)
        i = j
    return out


def is_shim_file(path, limit=20):
    """True if a file is only preprocessor glue -- a redirect, not content.

    MacSurf keeps a stub at the original name that includes the renamed real
    header: src/select/select.h is six lines of #include pointing at
    css_internal_select.h, which holds the actual 174 lines. Porting the stub
    overwrites upstream's real select.h with a redirect to a file we do not
    have, and every type it declared disappears.

    Skipping the stub lets renamed_and_modified carry the real content onto the
    upstream filename instead.
    """
    try:
        with open(path, errors='replace') as fh:
            body = [l.strip() for l in fh]
    except OSError:
        return False
    code = [l for l in body
            if l and not l.startswith(('/*', '*', '//', '*/'))]
    if not code or len(code) > limit:
        return False
    return all(l.startswith('#') for l in code)


INLINE_DEF = re.compile(r'^[ \t]*static[ \t]+inline\b', re.M)


def de_inlined(upstream_text, macsurf_text):
    """True if MacSurf removed this header's `static inline` definitions.

    Counts definitions at line start, not the substring: MacSurf leaves a
    comment reading "static inline bodies extracted to libdom_c89_helpers.c",
    and a naive `in` test sees that and concludes nothing was removed.
    """
    return (len(INLINE_DEF.findall(upstream_text)) > 0
            and len(INLINE_DEF.findall(macsurf_text)) == 0)


BOOL_SUB = re.compile(r'\bunsigned char\b')
LONE_BOOL = re.compile(r'^\+(\s*)unsigned char (\w+) = ([01]);\s*$')
# The corruption is an escaped quote where a string literal should BEGIN:
# `SLEN(\"text\")`. An escaped quote INSIDE a literal is legitimate --
# `fprintf(stream, "uri(\"%.*s\")", ...)` is correct C -- so require the
# match to be preceded by an identifier's opening paren with no earlier
# unescaped quote on the line.
BAD_ESCAPE = re.compile(r'^[^"]*\w\(\\"')
TRUE_SUB = re.compile(r'\btrue\b')
FALSE_SUB = re.compile(r'\bfalse\b')


def _bool_norm(text):
    """Normalise a declaration so the C89 and C99 spellings compare equal.

    MacSurf rewrites `bool x = false;` as `unsigned char x = 0;` -- the type
    AND the literal. Comparing only the type misses those, and one such line
    surviving is enough to fail the build.
    """
    text = BOOL_SUB.sub('bool', text)
    text = TRUE_SUB.sub('1', text)
    text = FALSE_SUB.sub('0', text)
    return text


def renumber_hunks(lines):
    """Recompute every @@ header from the body that follows it.

    Both rescue passes rewrite hunk bodies -- dropping a replacement line, or
    turning a removal into context -- and hand-reasoning about the resulting
    old/new counts is how you get "malformed patch" from GNU patch. Counting
    the body after the fact cannot drift.
    """
    out = []
    i = 0
    while i < len(lines):
        m = HUNK.match(lines[i].rstrip('\n'))
        if not m:
            out.append(lines[i])
            i += 1
            continue
        old_start, _, new_start, _, tail = m.groups()
        body, j = [], i + 1
        while j < len(lines):
            l = lines[j]
            if HUNK.match(l.rstrip('\n')) or l.startswith(('diff ', '--- ', '+++ ')):
                break
            body.append(l)
            j += 1
        # A hunk whose every change was rescued is now pure context. GNU
        # patch rejects a no-op hunk as malformed, so drop it entirely.
        if not any(l[:1] in '+-' and not l.startswith(('+++', '---'))
                   for l in body):
            i = j
            continue
        o = sum(1 for l in body if l[:1] in (' ', '-') or l == '\n')
        n = sum(1 for l in body if l[:1] in (' ', '+') or l == '\n')
        out.append(f'@@ -{old_start},{o} +{new_start},{n} @@{tail}\n')
        out.extend(body)
        i = j
    return out


def keep_bool_decls(lines):
    """Refuse to port `bool` -> `unsigned char` substitutions.

    CodeWarrior 8 in C89 mode has no `bool`, so MacSurf rewrote declarations to
    `unsigned char` throughout -- the same workaround as removing <stdbool.h>,
    but in the type rather than the include. On GCC it is worse than
    unnecessary: libwapcaplet's public API still takes `bool *`, so a caller
    with `unsigned char match;` fails with "initialization of '_Bool *' from
    incompatible pointer type".

    Where a removed line and the following added line differ only by that
    substitution, keep the original and drop the replacement.
    """
    out = []
    i = 0
    while i < len(lines):
        cur = lines[i]
        nxt = lines[i + 1] if i + 1 < len(lines) else ''
        if (cur.startswith('-') and nxt.startswith('+')
                and not cur.startswith('---') and not nxt.startswith('+++')
                and 'bool' in cur and 'unsigned char' in nxt
                and _bool_norm(nxt[1:]) == _bool_norm(cur[1:])):
            out.append(' ' + cur[1:])
            i += 2
            continue
        # Escaped-quote corruption. MacSurf's C89 declaration-splitting pass
        # mangled three files, leaving `SLEN(\"If-None-Match:\")` -- an opening
        # paren followed by an escaped quote, which is never valid C. They
        # never noticed because their CodeWarrior project does not compile
        # those files. Keep the upstream line instead.
        if (cur.startswith('-') and nxt.startswith('+')
                and not cur.startswith('---') and not nxt.startswith('+++')
                and BAD_ESCAPE.search(nxt)):
            out.append(' ' + cur[1:])
            i += 2
            continue

        # Unpaired case: MacSurf rewrote a whole function, so the C89
        # declaration arrives as a pure addition with no removal to pair with.
        # Only the exact scalar-initialised-to-0/1 idiom is rewritten; anything
        # with pointer or array syntax is left alone, since `unsigned char` is
        # a legitimate type in this codebase for byte buffers.
        m = LONE_BOOL.match(cur)
        if m:
            indent, name, val = m.groups()
            lit = 'true' if val == '1' else 'false'
            out.append(f'+{indent}bool {name} = {lit};\n')
            i += 1
            continue
        out.append(cur)
        i += 1
    return out


def is_pure_deletion(lines):
    """True if this file-diff only removes an upstream file.

    MacSurf deletes files only as a side effect of renaming them, and our
    rename detection cannot catch every scheme they used
    (stylesheet.h -> css_internal_stylesheet.h defeated three prefix rules).
    Keeping an upstream file we do not need is free; deleting one we do need
    breaks the build. So never port a deletion.
    """
    body = [l for l in lines
            if l[:1] in '+-' and not l.startswith(('+++', '---'))]
    return bool(body) and all(l.startswith('-') for l in body)


def find_renames(upstream, macsurf):
    """Return the set of MacSurf-side paths that are pure renames of an
    upstream file (identical content, different name)."""
    def index(root):
        m = collections.defaultdict(list)
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames
                           if d not in ('.git', 'test') and not d.startswith('build-')]
            for fn in filenames:
                if fn.endswith(('.c', '.h', '.inc')):
                    full = os.path.join(dirpath, fn)
                    sig = content_sig(full)
                    if sig:
                        m[sig].append(os.path.relpath(full, root))
        return m

    up, ms = index(upstream), index(macsurf)
    renamed = set()
    for sig, paths in ms.items():
        if sig in up:
            for p in paths:
                if p not in up[sig]:
                    renamed.add(p)
    # The upstream side of each rename shows up as a deletion; drop it too.
    for sig, paths in up.items():
        if sig in ms:
            for p in paths:
                if p not in ms[sig]:
                    renamed.add(p)
    return renamed


# CodeWarrior prefixes MacSurf added to dodge filename collisions.
# Must list every prefix MacSurf stacks, including the inner ones: stripping
# css_ off css_internal_select.h leaves internal_select.h, which matches
# nothing, so the rename is missed unless internal_ is strippable too.
RENAME_PREFIX = re.compile(
    r'^(ns_|hub_|pu_|dom_|css_|p_|s_|libcss_|libhubbub_|'
    r'internal_|utils_|core_)')
RENAME_SUFFIX = re.compile(r'_i\.h$')

# Only #include directives, blanks and comments. Guard macros are NOT noise:
# MacSurf adds `#ifndef MACSURF_CONTENT_DEBUG_ENUM` to content_type.h so the
# duplicate copy in browser_window.h compiles out. Treating that as include
# churn dropped it, the guard never got defined, and both definitions landed --
# "redeclaration of enum content_debug".
INCLUDE_ONLY = re.compile(r'^[+-]\s*(#\s*include\b|/\*|\*|//|$)')


def is_include_churn(lines):
    """True if a file's diff changes nothing but #include lines and guards.

    MacSurf's renames drag a rewritten #include through every file that
    referenced them. Since we keep upstream filenames, none of that applies to
    us -- porting it would break includes that are already correct.
    """
    changed = [l for l in lines
               if l[:1] in '+-' and not l.startswith(('+++', '---'))]
    if not changed:
        return False
    return all(INCLUDE_ONLY.match(l) for l in changed)


RENAME_PREFIXES = ('ns_', 'hub_', 'pu_', 'dom_', 'css_', 'p_', 's_',
                   'libcss_', 'libhubbub_', 'css_internal_', 'dom_utils_')


def strip_candidates(base):
    """Yield progressively prefix-stripped forms of a basename."""
    seen = set()
    cur = base
    while True:
        nxt = RENAME_PREFIX.sub('', cur, count=1)
        if nxt == cur or nxt in seen:
            break
        seen.add(nxt)
        cur = nxt
        yield nxt
        alt = RENAME_SUFFIX.sub('.h', nxt)
        if alt != nxt:
            yield alt


def is_rename_pair(rel, all_bases, ms_paths):
    """True if this path is either half of a prefix/suffix rename pair.

    Checked in both directions: the renamed file (event_i.h, ns_errors.h) and
    the upstream original it replaced (event.h, errors.h), which appears in the
    diff as a whole-file deletion.

    The reverse direction only applies when MacSurf actually dropped the file.
    Without that guard it fires on any upstream file that merely has a prefixed
    namesake somewhere, which silently excluded include/libcss/computed.h --
    present and modified in both trees -- and with it the
    css_computed_transition_data typedef the build needs.
    """
    base = os.path.basename(rel)

    # This file looks renamed -- does the original exist? Strip prefixes
    # repeatedly: MacSurf stacks them (css_ + internal_ = css_internal_select.h
    # from select.h), and removing only the first leaves a name that matches
    # nothing, so the rename is missed and the file ships as a spurious new one.
    for stem in strip_candidates(base):
        if stem in all_bases:
            return True

    if rel in ms_paths:
        return False              # MacSurf still has it: modified, not renamed

    # Dropped by MacSurf -- does a renamed variant exist?
    if base.endswith('.h') and base[:-2] + '_i.h' in all_bases:
        return True
    return any(pfx + base in all_bases for pfx in RENAME_PREFIXES)


def renamed_and_modified(lib, up_root, ms_root, index, already):
    """Diffs for files MacSurf both renamed AND changed.

    Excluding renames wholesale loses real work: css_internal_stylesheet.h is
    a rename of stylesheet.h, but it also adds the custom_properties member
    that MacSurf's cascade-time var() support needs. Dropping it compiles
    stylesheet.c against a struct missing the field.

    So for every MacSurf file that maps to a differently-named upstream file,
    diff the two and emit the change against the UPSTREAM path. The rename is
    still discarded; only the content change is carried.
    """
    import difflib
    out = []
    for dirpath, dirnames, filenames in os.walk(ms_root):
        dirnames[:] = [d for d in dirnames
                       if d not in ('.git', 'test') and not d.startswith('build-')]
        for fn in filenames:
            if not fn.endswith(('.c', '.h')):
                continue
            ms_path = os.path.join(dirpath, fn)
            rel = os.path.relpath(ms_path, ms_root)
            inner = re.sub(r'^(src|include)/', '', rel)
            if inner in index and index[inner] == inner:
                continue                      # same name both sides; already diffed
            # Resolve only within the SAME directory. Matching on basename
            # alone is ambiguous -- several libs carry more than one utils.c --
            # and a wrong match silently patches the wrong file.
            up_dir = os.path.join(up_root, os.path.dirname(rel))
            up_path = None
            for stem in strip_candidates(fn):
                cand = os.path.join(up_dir, stem)
                if os.path.exists(cand):
                    up_path = cand
                    break
            if up_path is None:
                continue
            try:
                a = open(up_path, errors='replace').readlines()
                b = open(ms_path, errors='replace').readlines()
            except OSError:
                continue
            if [x.split() for x in a] == [x.split() for x in b]:
                continue                      # pure rename, nothing to carry
            at, bt = ''.join(a), ''.join(b)
            if de_inlined(at, bt):
                # CW8 C89 has no `inline`, so MacSurf turned these definitions
                # into extern declarations and moved the bodies to a helper .c.
                # Porting that leaves the declarations without definitions --
                # `undefined reference to list_del` at link time.
                continue
            up_rel = os.path.relpath(up_path, up_root)
            if up_rel in already:
                continue      # the main diff already covers this file
            diff = list(difflib.unified_diff(
                a, b,
                fromfile=f'upstream/{lib}/{up_rel}',
                tofile=f'browser/{lib}/{up_rel}'))
            if diff:
                header = (f'diff -urN upstream/{lib}/{up_rel} '
                          f'browser/{lib}/{up_rel}\n')
                out.append((up_rel, [header] + diff))
    return out


def split_patch(path):
    """Yield (target_path, [lines]) per file-level diff in a unified patch."""
    cur, buf = None, []
    with open(path, errors='replace') as fh:
        for line in fh:
            if line.startswith('diff '):
                if cur:
                    yield cur, buf
                cur, buf = line.split()[-1], [line]
            elif cur:
                buf.append(line)
    if cur:
        yield cur, buf


def topic_for(lib, rel):
    """Map a source file to a patch topic. Whole files only, so no two patches
    ever touch the same file and the stack applies in any order."""
    base = os.path.basename(rel)
    m = re.match(r'[ps]_macsurf_(.+)\.c$', base)
    if m:
        return 'property-' + m.group(1).replace('_', '-')
    if base in ('Makefile', 'Makefile.config'):
        return 'build'
    if rel.endswith('.gen'):
        return 'generator-input'
    d = os.path.dirname(rel)
    for prefix, topic in (
        # netsurf core: the layout engine and plotters are the point of the
        # port, so they get their own topics rather than landing in 'misc'.
        ('content/handlers/html', 'html-layout'),
        ('content/handlers/css', 'css-handler'),
        ('content/handlers/image', 'image-handlers'),
        ('content/handlers/javascript', 'javascript'),
        ('content/handlers/text', 'text-handler'),
        ('content/fetchers', 'fetchers'),
        ('content', 'content-core'),
        ('desktop', 'desktop'),
        ('include/netsurf', 'public-headers'),
        ('utils', 'utils'),
        ('src/select/properties', 'select-properties'),
        ('src/select', 'select-cascade'),
        ('src/parse/properties', 'parse-properties'),
        ('src/parse', 'parse-core'),
        ('src/tokeniser', 'tokeniser'),
        ('src/treebuilder', 'treebuilder'),
        ('src/charset', 'charset'),
        ('src/utils', 'utils'),
        ('src/core', 'core'),
        ('src/events', 'events'),
        ('src/html', 'html'),
        ('bindings', 'bindings'),
        ('include', 'public-headers'),
        ('src/lex', 'lexer'),
        ('src/bytecode', 'bytecode'),
        ('src', 'misc'),
    ):
        if d.startswith(prefix):
            return topic
    return 'misc'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work', default=os.path.expanduser('<WORK>/vitabrowser-work'))
    ap.add_argument('--out', default='patches')
    args = ap.parse_args()

    src = os.path.join(args.work, 'patches')
    if not os.path.isdir(src):
        print(f'no {src} -- run tools/regen-patches.sh first', file=sys.stderr)
        return 2

    os.makedirs(args.out, exist_ok=True)
    manifest = []
    totals = collections.Counter()

    for lib in LIBS:
        patch = os.path.join(src, f'{lib}.patch')
        if not os.path.exists(patch):
            continue
        up_root = os.path.join(args.work, 'upstream', lib)
        ms_root = os.path.join(args.work, 'browser', lib)
        renamed = find_renames(up_root, ms_root)
        ms_paths = set()
        for dirpath, dirnames, filenames in os.walk(ms_root):
            dirnames[:] = [d for d in dirnames
                           if d not in ('.git', 'test')
                           and not d.startswith('build-')]
            for fn in filenames:
                ms_paths.add(os.path.relpath(os.path.join(dirpath, fn), ms_root))

        tracked = upstream_tracked(up_root)
        index = build_include_index(up_root)
        # Basename swaps for non-include references, chiefly Makefile source
        # lists that would otherwise name renames we did not port.
        basename_map = {}
        for dirpath, dirnames, filenames in os.walk(ms_root):
            dirnames[:] = [d for d in dirnames
                           if d not in ('.git', 'test')
                           and not d.startswith('build-')]
            rel_dir = os.path.relpath(dirpath, ms_root)
            for fn in filenames:
                if not fn.endswith('.c'):
                    continue
                # Same-directory only. Basename matching across directories
                # renames s_accent_color.c (a MacSurf addition in
                # src/select/properties) onto src/parse/properties/accent_color.c
                # and the Makefile then names a file that is never built.
                for stem in strip_candidates(fn):
                    if os.path.exists(os.path.join(up_root, rel_dir, stem)):
                        basename_map[fn] = stem
                        break
        # Every basename present on either side, so a prefix/suffix variant
        # can be recognised as the counterpart of a real upstream file.
        rename_bases = set()
        for root in (os.path.join(args.work, 'upstream', lib),
                     os.path.join(args.work, 'browser', lib)):
            for dirpath, dirnames, filenames in os.walk(root):
                dirnames[:] = [d for d in dirnames
                               if d not in ('.git', 'test')
                               and not d.startswith('build-')]
                rename_bases.update(filenames)

        topics = collections.defaultdict(list)
        emitted = set()
        skipped = collections.Counter()

        for target, lines in split_patch(patch):
            rel = target.split(f'/{lib}/', 1)[-1]
            churn = sum(1 for l in lines
                        if l[:1] in '+-' and not l.startswith(('+++', '---')))
            if rel in renamed:
                skipped['rename'] += churn
                continue
            if is_generated(rel, tracked):
                skipped['generated'] += churn
                continue
            # MacSurf vendors CodeWarrior-flattened copies of the library
            # public headers into netsurf/include/{dom,hubbub,parserutils,...}
            # so the CW project can find them. Upstream netsurf only has
            # include/netsurf. We install the real headers into a prefix, and
            # these copies SHADOW them -- netsurf/include/dom/dom.h includes
            # dom/events/dom_events.h, a name that only exists in MacSurf's
            # flattened world. Never port them.
            if lib == 'netsurf' and rel.startswith('include/') \
                    and not rel.startswith('include/netsurf/'):
                skipped['vendored-headers'] += churn
                continue
            if is_rename_pair(rel, rename_bases, ms_paths):
                skipped['rename'] += churn
                continue
            if is_include_churn(lines):
                skipped['include-rewrite'] += churn
                continue
            if is_pure_deletion(lines):
                skipped['deletion'] += churn
                continue
            up_file = os.path.join(up_root, rel)
            ms_file = os.path.join(ms_root, rel)
            if os.path.exists(up_file) and os.path.exists(ms_file):
                try:
                    at = open(up_file, errors='replace').read()
                    bt = open(ms_file, errors='replace').read()
                except OSError:
                    at = bt = ''
                if de_inlined(at, bt):
                    skipped['c89-workaround'] += churn
                    continue
            if is_shim_file(os.path.join(ms_root, rel)):
                skipped['shim'] += churn
                continue
            # MacSurf marks its CodeWarrior C89 workarounds in the filename.
            # libdom_c89_helpers.c exists only to hold function bodies moved
            # out of headers because CW8 has no `inline`. GCC does.
            if 'c89' in os.path.basename(rel).lower():
                skipped['c89-workaround'] += churn
                continue
            fixes = set()
            for l in lines:
                if l.startswith('+'):
                    fixes.update(f.lower() for f in FIX_RE.findall(l))
            # A file carrying exactly one fix id can be attributed to that fix,
            # which is the finest honest granularity the source supports. Files
            # with none, or with several interleaved, stay in the topic patch:
            # splitting those would need hunk surgery and would produce patches
            # that no longer apply independently.
            key = (topic_for(lib, rel),
                   sorted(fixes)[0] if len(fixes) == 1 else None)
            emitted.add(rel)
            topics[key].append(
                (rel, rewrite_includes(lines, index, basename_map), churn))

        # Carried-over content from renamed-and-modified files. These are
        # synthesised against upstream paths and are rename-free by
        # construction, so they skip the exclusion filters above.
        for rel, lines in renamed_and_modified(lib, up_root, ms_root,
                                               index, emitted):
            churn = sum(1 for l in lines
                        if l[:1] in '+-' and not l.startswith(('+++', '---')))
            if not churn:
                continue
            fixes = set()
            for l in lines:
                if l.startswith('+'):
                    fixes.update(f.lower() for f in FIX_RE.findall(l))
            key = (topic_for(lib, rel),
                   sorted(fixes)[0] if len(fixes) == 1 else None)
            emitted.add(rel)
            topics[key].append(
                (rel, rewrite_includes(lines, index, basename_map), churn))
            totals['carried'] += churn

        # Clear only this library's generated patches. Never wipe args.out
        # wholesale: patches/vitabrowser/ is hand-maintained port work that
        # the splitter cannot reproduce, and losing it silently un-fixes the
        # build (the cascade symbols come back undefined).
        libdir = os.path.join(args.out, lib)
        if os.path.isdir(libdir):
            for stale in os.listdir(libdir):
                if stale.endswith('.patch'):
                    os.unlink(os.path.join(libdir, stale))
        os.makedirs(libdir, exist_ok=True)
        def order(k):
            return (k[0], k[1] or '')

        for n, key in enumerate(sorted(topics, key=order), start=1):
            topic, fix = key
            entries = sorted(topics[key])
            churn = sum(e[2] for e in entries)
            fixes = set()
            body = []
            for rel, lines, _ in entries:
                body.extend(lines)
                for l in lines:
                    if l.startswith('+'):
                        fixes.update(f.lower() for f in FIX_RE.findall(l))
            name = (f'{n:02d}-{topic}-{fix}.patch' if fix
                    else f'{n:02d}-{topic}.patch')
            with open(os.path.join(libdir, name), 'w') as fh:
                fh.write(f'# {lib}: {topic}' + (f' [{fix}]\n' if fix else '\n'))
                fh.write(f'# {len(entries)} files, {churn} changed lines\n')
                if fixes:
                    fh.write(f'# MacSurf fix ids: {" ".join(sorted(fixes))}\n')
                fh.write('#\n# Regenerate: tools/regen-patches.sh && tools/split-patches.py\n#\n')
                fh.writelines(body)
            manifest.append((lib, name, len(entries), churn, len(fixes)))
            totals['ported'] += churn
        for k, v in skipped.items():
            totals[k] += v

    with open(os.path.join(args.out, 'MANIFEST.md'), 'w') as fh:
        fh.write('# MacSurf patch stack\n\n')
        fh.write('Generated by `tools/split-patches.py`. Do not hand-edit; '
                 'edit the source trees and regenerate.\n\n')
        fh.write('| Library | Patch | Files | Lines | Fix ids |\n')
        fh.write('|---|---|---:|---:|---:|\n')
        for lib, name, nf, churn, nfix in manifest:
            fh.write(f'| {lib} | `{name}` | {nf} | {churn} | {nfix} |\n')
        fh.write(f'\n**Ported: {totals["ported"]} lines** in {len(manifest)} patches.\n\n')
        fh.write('Excluded as carrying no semantic value for a GCC/vitaSDK target:\n\n')
        fh.write(f'- **{totals["rename"]} lines** of CodeWarrior renames\n')
        fh.write(f'- **{totals["generated"]} lines** of committed build output\n')
        fh.write(f'- **{totals["include-rewrite"]} lines** of #include rewrites '
                 f'chasing those renames\n')
        fh.write(f'- **{totals["deletion"]} lines** of whole-file deletions, which '
                 f'MacSurf only ever does as the far side of a rename\n')
        fh.write(f'- **{totals["shim"]} lines** of redirect stubs left at the '
                 f'original filename, pointing at the renamed real header\n')
        fh.write(f'- **{totals["c89-workaround"]} lines** of CodeWarrior C89 '
                 f'workarounds (function bodies moved out of headers that GCC '
                 f'compiles as-is)\n')
        fh.write(f'- **{totals["vendored-headers"]} lines** of library public '
                 f'headers vendored into netsurf/include, which shadow the '
                 f'real installed ones\n')
        fh.write(f'\nOf the ported total, **{totals["carried"]} lines** were '
                 f'recovered from files MacSurf both renamed and modified, and '
                 f're-targeted at the upstream filename.\n')

    print(f'{len(manifest)} patches, {totals["ported"]} lines ported')
    print(f'excluded: {totals["rename"]} rename, {totals["generated"]} generated, '
          f'{totals["include-rewrite"]} include-rewrite, {totals["deletion"]} deletion, '
          f'{totals["shim"]} shim')
    return 0


if __name__ == '__main__':
    sys.exit(main())
